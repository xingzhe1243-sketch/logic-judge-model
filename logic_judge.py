        cfg = CONFIG
        self.api_key = api_key or cfg["api_key"] or os.environ.get("DEEPSEEK_API_KEY", "")
        self.base_url = cfg["base_url"]
        self.model = model or cfg["model"]

        if not self.api_key:
            print("[!] 未设置 DEEPSEEK_API_KEY，将使用本地知识库分析（无 LLM 增强）", file=sys.stderr)
            self.client = None
        else:
            self.client = OpenAI(
                api_key=self.api_key,
                base_url=self.base_url
            )
        self.kb = KNOWLEDGE_BASE

