        # 因果论证 (规则18-21)
        causal_words = ["导致", "引起", "造成", "因为", "所以", "促使"]
        if any(w in text for w in causal_words):
            analysis["因果论证评估"].append("检测到因果论证:")
            analysis["因果论证评估"].append("  规则18: 因果论证始于关联 — 是否建立了可靠的相关性？")
