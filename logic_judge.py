def _load_config():
    """从 .env 文件和环境变量加载配置"""
    config = {
        "api_key": os.environ.get("DEEPSEEK_API_KEY", ""),
        "model": os.environ.get("DEEPSEEK_MODEL", "deepseek-reasoner"),
        "base_url": os.environ.get("DEEPSEEK_BASE_URL", "https://api.deepseek.com/v1")
    }

    # 尝试从 .env 文件读取
    env_paths = [
        os.path.join(os.path.dirname(os.path.abspath(__file__)), ".env"),
        os.path.join(os.path.expanduser("~"), ".logic_judge.env")
    ]
    for env_path in env_paths:
        if os.path.exists(env_path):
            with open(env_path, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line or line.startswith("#") or "=" not in line:
                        continue
                    key, _, val = line.partition("=")
                    key = key.strip().upper()
                    val = val.strip().strip("\"'")
                    if key == "DEEPSEEK_API_KEY" and not config["api_key"]:
                        config["api_key"] = val
                    elif key == "DEEPSEEK_MODEL" and not os.environ.get("DEEPSEEK_MODEL"):
                        config["model"] = val
                    elif key == "DEEPSEEK_BASE_URL" and not os.environ.get("DEEPSEEK_BASE_URL"):
                        config["base_url"] = val
            break

    return config

CONFIG = _load_config()

