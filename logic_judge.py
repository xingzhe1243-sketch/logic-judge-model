def interactive_mode():
    """交互式分析 CLI"""
    print("\n" + "#" * 60)
    print("#  终极逻辑判断模型 . 九维思维矩阵")
    print("#" + " " * 20 + "整合9本经典著作的思维框架")
    print("#" * 60)
    print()

    judge = LogicJudgeModel()

    print("\n支持的命令：")
    print("  analyze <文本>  — 全面逻辑分析")
    print("  syllogism       — 三段论验证")
    print("  causal          — 因果分析")
    print("  models          — 查看所有知识库模型")
    print("  help            — 帮助")
    print("  exit/quit       — 退出")
    print()

    reasoning = ReasoningEngine()

    while True:
        try:
            cmd = input("\n🔍 ").strip()
            if not cmd:
                continue
            if cmd in ("exit", "quit"):
                print("再见！")
                break
            elif cmd == "help":
                print("可用命令同上。也可输入原始文本直接开始分析。")
            elif cmd == "models":
                for name, info in KNOWLEDGE_BASE.items():
                    print(f"  {name}: {info['source']}")
            elif cmd.startswith("analyze "):
                text = cmd[8:]
                judge.analyze(text)
            elif cmd == "syllogism":
                print("三段论验证器")
                major = input("  大前提: ")
                minor = input("  小前提: ")
                conc = input("  结论: ")
                result = reasoning.syllogism_check(major, minor, conc)
                print(f"  有效: {result['有效']}")
                for a in result["分析"]:
                    print(f"  {a}")
            elif cmd == "causal":
                claim = input("  因果陈述: ")
                result = reasoning.analyze_causal(claim)
                print(f"  原因: {result['原因']}")
                print(f"  结果: {result['结果']}")
                print(f"  需排除: {result['替代解释']}")
            else:
                # 默认当作文本分析
                judge.analyze(cmd)

        except KeyboardInterrupt:
            print("\n再见！")
            break
        except Exception as e:
            print(f"错误: {e}")


def main():
    """入口"""
    args = sys.argv[1:]
    json_mode = "--json" in args or "-j" in args
    if json_mode:
        args = [a for a in args if a not in ("--json", "-j")]

    if args:
        text = " ".join(args)
        judge = LogicJudgeModel()
        result = judge.analyze(text, verbose=not json_mode)
        if json_mode:
            print(json.dumps(result, ensure_ascii=True, indent=2))
    else:
        interactive_mode()


if __name__ == "__main__":
    main()
