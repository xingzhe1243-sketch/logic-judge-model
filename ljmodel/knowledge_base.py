_books_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "books")


def _load_books():
    """扫描 books/*.yaml，返回 {name: data} 字典"""
    import yaml
    books = {}
    pattern = os.path.join(_books_dir, "*.yaml")
    for fpath in sorted(glob.glob(pattern)):
        name = os.path.splitext(os.path.basename(fpath))[0]
        try:
            with open(fpath, "r", encoding="utf-8") as f:
                data = yaml.safe_load(f)
            if isinstance(data, dict):
                books[name] = data
        except Exception as e:
            print(f"[knowledge_base] 加载书籍失败 {fpath}: {e}")
    return books


def _build_knowledge_base():
    """将 YAML 书籍合并到默认知识库上（YAML 优先级更高）"""
    kb = dict(_DEFAULT_KNOWLEDGE_BASE)
    yaml_books = _load_books()
    for key, value in yaml_books.items():
        # YAML 文件完全替换对应 key 的整个内容
        kb[key] = value
    return kb


KNOWLEDGE_BASE = _build_knowledge_base()


def reload_books():
    """运行时重新加载 books/*.yaml（不重启进程）"""
    global KNOWLEDGE_BASE
    KNOWLEDGE_BASE = _build_knowledge_base()
    yaml_books = _load_books()
    return list(yaml_books.keys())
